import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const read = (path) =>
  readFileSync(path, "utf8")
    .replace(/\r\n/g, "\n")
    .replace(/[ \t]+$/gm, "")
    .trim();
const hash = (text) => createHash("sha256").update(text).digest("hex");
const overridesDir = join(root, "scripts/license-overrides");
const overrides = JSON.parse(read(join(overridesDir, "manifest.json")));
const groups = new Map();

function licenseTexts(directory, id) {
  let texts = readdirSync(directory, { withFileTypes: true })
    .filter(
      (file) =>
        file.isFile() &&
        /^(licen[sc]e|copying|copyright|notice|unlicen[sc]e)([._-]|$)/i.test(
          file.name,
        ),
    )
    .map((file) => read(join(directory, file.name)))
    .filter(Boolean);
  for (const name of ["LICENSES", "licenses"]) {
    const folder = join(directory, name);
    if (existsSync(folder)) {
      texts.push(
        ...readdirSync(folder, { withFileTypes: true })
          .filter((file) => file.isFile())
          .map((file) => read(join(folder, file.name)))
          .filter(Boolean),
      );
    }
  }
  if (!texts.length && overrides[id]) {
    const entry = overrides[id];
    const bytes = readFileSync(join(overridesDir, entry.file));
    if (hash(bytes) !== entry.sha256)
      throw new Error(`License override changed: ${id}`);
    texts = [bytes.toString("utf8").trim()];
  }
  if (!texts.length)
    throw new Error(
      `No license text for ${id}; review upstream and add a version-pinned override.`,
    );
  return [...new Set(texts)].sort().join("\n\n");
}

function add(id, license, directory, source) {
  if (!license) throw new Error(`Missing license declaration: ${id}`);
  const text = licenseTexts(directory, id);
  const key = hash(text);
  if (!groups.has(key)) groups.set(key, { text, packages: [] });
  groups
    .get(key)
    .packages.push(
      `${id}\nLicense: ${license}\nSource: ${source || "See upstream package source"}`,
    );
}

const lock = JSON.parse(read(join(root, "package-lock.json")));
for (const [path, pkg] of Object.entries(lock.packages)) {
  if (!path || pkg.dev) continue;
  const name = pkg.name || path.split("node_modules/").at(-1);
  add(
    `npm:${name}@${pkg.version}`,
    pkg.license,
    join(root, path),
    pkg.resolved,
  );
}
const metadata = JSON.parse(
  execFileSync(
    process.env.CARGO || "cargo",
    [
      "metadata",
      "--locked",
      "--format-version",
      "1",
      "--manifest-path",
      join(root, "src-tauri/Cargo.toml"),
    ],
    { encoding: "utf8", maxBuffer: 32 * 1024 * 1024 },
  ),
);
for (const pkg of metadata.packages) {
  if (pkg.name === "codexdeck") continue;
  add(
    `cargo:${pkg.name}@${pkg.version}`,
    pkg.license,
    dirname(pkg.manifest_path),
    pkg.repository,
  );
}
const sections = [...groups.values()]
  .map(({ text, packages }) => `${packages.sort().join("\n\n")}\n\n${text}`)
  .sort();
const output =
  [
    "CodexDeck third-party notices",
    "Generated by npm run licenses:generate. Do not edit this file manually.",
    "Includes production npm dependencies and the complete locked Rust graph (all platforms, including build dependencies). Some listed components are not shipped on every platform.",
    "License alternatives remain as declared by upstream; inclusion of an alternative's text does not require choosing all alternatives. System frameworks and separately installed Codex CLI are not redistributed here.",
    "MPL-2.0 component source: selectors 0.38.0, https://github.com/servo/stylo/tree/572ecba2d1600e7c3d490586692a209faf703baa/selectors . Obtain the corresponding source from that revision. CodexDeck does not modify selectors.",
    "Locally patched glib 0.18.5 source is distributed in vendor/glib in the CodexDeck source repository. See vendor/README.md for provenance and patch details.",
    ...sections,
  ].join("\n\n" + "=".repeat(72) + "\n\n") + "\n";
const destination = join(root, "public/licenses/third-party-notices.txt");
if (process.argv.includes("--check")) {
  if (
    !existsSync(destination) ||
    readFileSync(destination, "utf8") !== output
  ) {
    throw new Error(
      "Third-party notices are stale. Run npm run licenses:generate and commit the result.",
    );
  }
  console.log("Third-party notices match the locked dependencies.");
} else {
  writeFileSync(destination, output);
  console.log(
    `Generated ${resolve(destination)} (${metadata.packages.length - 1} Rust packages).`,
  );
}
